'use client';

import { useSelector } from 'react-redux';

import { useCallback, useState } from 'react';
import { getName } from '@init-globals';
import type { ClientComponent } from '@types';
import type { ReduxProps, StorePatientState } from '@store-types';
import { CircleSpinner } from 'react-spinners-kit';
import { IoDownload } from '@react-icons/all-files/io5/IoDownload';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { FaPhone } from '@react-icons/all-files/fa/FaPhone';
import { useRouter } from 'next/navigation';
import { useUser } from '@selectors';

// Inline star rating display for analytics
const StarRating = ({ rating }: { rating: number | null | undefined }) => {
  if (!rating) {
    return (
      <span
        className="inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium"
        style={{
          background: 'rgba(107,114,128,0.12)',
          color: '#6B7280',
          border: '1px solid rgba(107,114,128,0.2)',
        }}
      >
        N/A
      </span>
    );
  }
  return (
    <div className="flex items-center gap-0.5">
      {[1, 2, 3, 4, 5].map((i) => (
        <svg
          key={i}
          xmlns="http://www.w3.org/2000/svg"
          viewBox="0 0 24 24"
          className="w-4 h-4"
          fill={i <= rating ? '#ef233c' : 'none'}
          stroke={i <= rating ? '#ef233c' : '#D1D5DB'}
          strokeWidth={1.5}
        >
          <path
            strokeLinecap="round"
            strokeLinejoin="round"
            d="M11.48 3.499a.562.562 0 011.04 0l2.125 5.111a.563.563 0 00.475.345l5.518.442c.499.04.701.663.321.988l-4.204 3.602a.563.563 0 00-.182.557l1.285 5.385a.562.562 0 01-.84.61l-4.725-2.885a.563.563 0 00-.586 0L6.982 20.54a.562.562 0 01-.84-.61l1.285-5.386a.562.562 0 00-.182-.557l-4.204-3.602a.562.562 0 01.321-.988l5.518-.442a.563.563 0 00.475-.345L11.48 3.5z"
          />
        </svg>
      ))}
      <span className="ml-1 text-xs font-medium text-gray-500">({rating})</span>
    </div>
  );
};

const RenderTable: ClientComponent = () => {

  const { setPatientAppointmentsListing } = useSelector<any, any>(
    (state) => state.patients
  );
  const router = useRouter();
  const [user] = useUser();

  const handleDownload = (observation: any, organizer: any) => {

    const doc = new jsPDF();

    // Header Title
    doc.setFontSize(16);
    doc.setFont('helvetica', 'bold');
    doc.text('Medical Appointment Observation Report', 105, 20, { align: 'center' });

    // Table Content
    autoTable(doc, {
      startY: 40,
      theme: 'grid',
      headStyles: {
        fillColor: [22, 160, 133],
        textColor: 255,
        fontStyle: 'bold',
      },
      bodyStyles: {
        fontSize: 11,
      },
      columnStyles: {
        0: { cellWidth: 50 },
        1: { cellWidth: 130 },
      },
      head: [['Field', 'Details']],
      body: [
        ['Patient Name', `${organizer?.first_name || ''} ${organizer?.last_name || ''}`.trim() || 'N/A'],
        ['Observations', observation?.observations || 'N/A'],
        ['Diagnosis', observation?.diagnosis || 'N/A'],
        ['Medications', observation?.medications || 'N/A'],
        ['Procedure', observation?.procedure || 'N/A'],
        [
          'Follow-up Date',
          observation?.follow_up_date ? new Date(observation.follow_up_date).toLocaleDateString() : 'N/A',
        ],
      ],
    });

    // Footer
    doc.setFontSize(10);
    doc.text('Generated by HealthCare System', 20, 285);
    doc.text(`Date: ${new Date().toLocaleDateString()}`, 160, 285);

    doc.save('appointment_observation.pdf');
  };

  return (
    <>
      {setPatientAppointmentsListing?.map((el: any) => {
        const appointment = el?.appointment;
        const organizer = el?.appointment?.organizer;
        const observation = el?.appointment?.appointmentObservation;
        // Support both flat and nested feedback structures
        const feedbackRating = el?.appointment?.rating ?? el?.appointment?.rating ?? null;

        return (
          <tr
            key={el?.id}
            className="cursor-pointer border-b odd:bg-white even:bg-gray-50 hover:bg-gray-200"
          >
            <td className="px-6 py-4">{appointment?.title}</td>
            <td className="px-6 py-4">{appointment?.description || 'N/A'}</td>
            <td className="px-6 py-4">{appointment?.type}</td>
            <td className="px-6 py-4">
              {new Date(appointment?.start_date).toLocaleDateString()}
            </td>
            <td className="px-6 py-4">
              {new Date(appointment?.start_date).toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' })}
            </td>
            <td className="px-6 py-4">{el?.status}</td>
            <td className="px-6 py-4">{observation?.diagnosis || 'N/A'}</td>
            <td className="px-6 py-4">
              {organizer?.first_name} {organizer?.last_name}
            </td>

            {/* Feedback column */}
            <td className="px-6 py-4">
              <StarRating rating={feedbackRating} />
            </td>

            <td className="px-6 py-4">
              <div className="flex gap-2">
                <div
                  onClick={() => {
                    if (observation) handleDownload(observation, organizer);
                  }}
                  className={`theme-bg-color flex h-8 w-8 items-center justify-center rounded-full text-white transition duration-200 hover:scale-[110%] ${!observation ? 'opacity-50 cursor-not-allowed' : 'cursor-pointer'
                    }`}
                  title={observation ? 'Download' : 'Report not generated'}
                >
                  <IoDownload size={16} color={observation ? 'white' : '#A0AEC0'} />
                </div>
                <div
                  onClick={() => {
                    if (appointment?.id && user?.type) {
                      router.push(`/${user.type.toLowerCase()}/telemed/meetings/view/${appointment.id}`);
                    }
                  }}
                  className={`bg-green-500 flex h-8 w-8 items-center justify-center rounded-full text-white transition duration-200 hover:scale-[110%] ${!appointment?.id ? 'opacity-50 cursor-not-allowed' : 'cursor-pointer'}`}
                  title={appointment?.id ? 'Join Meeting' : 'Meeting not available'}
                >
                  <FaPhone size={16} />
                </div>
              </div>
            </td>
          </tr>
        );
      })}
    </>
  );
};

export default RenderTable;
